import {
  WIRELESS_REGISTRATION_GROUP_ID,
  WIRELESS_REGISTRATION_GROUP_NAME,
  WIRELESS_REGISTRATION_TEMPLATE_ID,
  type RegistrationContact,
  type RegistrationRecord,
  type RegistrationValues,
} from '@/views/tickets/types/businessRegistration';

type SeedSpec = {
  no: string;
  status: RegistrationRecord['status'];
  builder: string;
  handler: string;
  createdAt: string;
  updatedAt: string;
  closedAt?: string;
  values: Partial<RegistrationValues>;
  reminders?: RegistrationRecord['reminders'];
  contacts?: RegistrationContact[];
};

function fullValues(patch: Partial<RegistrationValues>): RegistrationValues {
  const base: RegistrationValues = {
    businessPhone: '',
    contactPhone: '',
    feedback: '',
    specificSource: '',
    channelDetail: '',
    accessTime: '',
    timeLimit: '24小时',
    upstreamNo: '',
    businessLine: '数字娱乐业务部',
    productCategory: '',
    productName: '',
    operator: '移动',
    province: '安徽省',
    orderTime: '',
    problemL1: '不知情订购',
    problemL2: '退订+退费',
    requestType: '',
    complaintType: '普通投诉',
    closedLoop: '待运营商回访确认',
    description: '',
    processResult: '',
    refundPhone: '',
    refundAmount: '',
    replyTime: '',
  };
  return { ...base, ...patch };
}

function recordOf(spec: SeedSpec): RegistrationRecord {
  const values = fullValues(spec.values);
  if (!values.replyTime) values.replyTime = spec.updatedAt;
  if (!values.accessTime) values.accessTime = spec.createdAt.replace(' ', 'T');
  return {
    no: spec.no,
    revision: 0,
    templateId: WIRELESS_REGISTRATION_TEMPLATE_ID,
    values,
    status: spec.status,
    groupId: WIRELESS_REGISTRATION_GROUP_ID,
    groupName: WIRELESS_REGISTRATION_GROUP_NAME,
    builder: spec.builder,
    handler: spec.handler,
    createdAt: spec.createdAt,
    updatedAt: spec.updatedAt,
    closedAt: spec.closedAt,
    history: [
      {
        id: `seed-hist-${spec.no}`,
        action: spec.status === '已结案' ? '结案' : '创建工单',
        actor: spec.builder,
        at: spec.createdAt,
        detail: spec.status === '已结案' ? values.processResult || '演示结案' : '无线音乐运营商登记演示数据',
      },
    ],
    attachments: [],
    contacts: spec.contacts ?? [],
    notifications: [],
    reminders: spec.reminders,
  };
}

